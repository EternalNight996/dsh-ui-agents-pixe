export function hash(s) {
  let seed = 0
  for (let i = 0; i < s.length; i++) seed = (seed * 31 + s.charCodeAt(i)) >>> 0
  return seed
}

export function cnameOf(id, div) {
  const pool = DIVISION_NAMES[div] || FALLBACK
  const h = hash(id)
  return pool[h % pool.length]
}

/* 给一批角色记录（{id, div}）生成稳定 id→cname 映射（按分部排序分配，同分部不重名直到池尽）。 */
export function cnameMap(records) {
  const byDiv = new Map()
  for (const r of records) {
    if (!byDiv.has(r.div)) byDiv.set(r.div, [])
    const list = byDiv.get(r.div)
    if (!list.includes(r.id)) list.push(r.id)
  }
  const map = {}
  for (const [div, ids] of byDiv) {
    const pool = DIVISION_NAMES[div] || FALLBACK
    ids.sort()
    ids.forEach((id, i) => { map[id] = pool[i % pool.length] })
  }
  return map
}
